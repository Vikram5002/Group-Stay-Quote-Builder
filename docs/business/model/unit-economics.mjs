// Unit-economics model for the pricing options (blueprint 16.3, 16.4). Plain Node, no deps.
// Run: node docs/business/model/unit-economics.mjs > docs/business/model/output.md
import { readFileSync } from 'node:fs';

const i = JSON.parse(readFileSync(new URL('./inputs.json', import.meta.url), 'utf8'));
const v = (k) => i[k].value;
const inr = (n) => `₹${Math.round(n).toLocaleString('en-IN')}`;
const supportCost = (v('support_minutes_per_property') / 60) * v('support_cost_per_hour_inr');

const lines = [];
const out = (s = '') => lines.push(s);

out('# Unit-economics model output');
out('');
out('Generated by `unit-economics.mjs` from `inputs.json`. Inputs marked Assumption are untested;');
out('read every row as "if these assumptions hold". Nothing here is a measured result.');
out('');
out(
  `Cost to serve per property per month = AWS cost + support (${v('support_minutes_per_property')} min at ${inr(v('support_cost_per_hour_inr'))}/h = ${inr(supportCost)}).`,
);
out('');
out('## A. Per-property subscription');
out('');
out(
  '| Price | AWS cost | Cost to serve | Gross margin | Break-even properties (fixed ' +
    inr(v('fixed_costs_inr')) +
    ') |',
);
out('| ----- | -------- | ------------- | ------------ | ------------------------------- |');
for (const price of v('price_points_inr')) {
  for (const aws of v('aws_cost_per_property_inr')) {
    const cost = aws + supportCost;
    const margin = (100 * (price - cost)) / price;
    const unit = price - cost;
    const breakEven =
      unit > 0 ? Math.ceil(v('fixed_costs_inr') / unit) : '∞ (loses money per property)';
    out(`| ${inr(price)} | ${inr(aws)} | ${inr(cost)} | ${margin.toFixed(1)}% | ${breakEven} |`);
  }
}
out('');
out('## B. Per-confirmed-group fee');
out('');
const fee = (v('per_group_fee_pct') / 100) * v('fixture_group_contribution_inr');
out(
  `${v('per_group_fee_pct')}% of a fixture-size group's contribution (${inr(v('fixture_group_contribution_inr'))}) = ${inr(fee)} per confirmed group.`,
);
out('');
out('| Groups confirmed / month | Revenue / property / month |');
out('| ------------------------ | -------------------------- |');
for (const g of v('groups_confirmed_per_month')) out(`| ${g} | ${inr(g * fee)} |`);
out('');
out('## Value to the hotel: payback of a subscription');
out('');
out(
  `Each prevented sub-floor confirmation protects ${inr(v('protected_contribution_per_prevented_breach_inr'))} of contribution (T05). How often that happens is unknown (H2).`,
);
out('');
out('| Prevented breaches / month | Protected / month | Pays back ₹999? | ₹1,999? | ₹2,999? |');
out('| -------------------------- | ----------------- | --------------- | ------- | ------- |');
for (const b of v('prevented_breaches_per_month')) {
  const p = b * v('protected_contribution_per_prevented_breach_inr');
  const ok = (price) => (p >= price ? 'yes' : 'no');
  out(`| ${b} | ${inr(p)} | ${ok(999)} | ${ok(1999)} | ${ok(2999)} |`);
}
out('');
out('**Reading:** the subscription case stands if a hotel prevents roughly one bad discount every');
out('two to six months at these prices; if breaches are rarer, value must come from speed (H1) or');
out('avoided double bookings (H3). The interviews exist to find that frequency.');
console.log(lines.join('\n'));
